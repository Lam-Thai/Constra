import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Constra",
  description: "Construction drawing annotation tool",
};

// Runs before hydration (synchronous <head> script, blocks parsing) so the
// correct theme is on <html data-theme="..."> before the first paint —
// avoids a flash of the wrong theme. Reads a stored preference, falling
// back to the OS setting on first visit. Wrapped in try/catch since
// localStorage/matchMedia can throw in locked-down environments.
const THEME_INIT_SCRIPT = `(function(){try{var s=localStorage.getItem('constra-theme');var t=s==='light'||s==='dark'?s:(window.matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light');document.documentElement.setAttribute('data-theme',t);}catch(e){}})();`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable}`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
      </head>
      <body>{children}</body>
    </html>
  );
}
